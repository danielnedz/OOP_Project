package bg.tu_varna.sit.f24621853.project11.command;

/**
 * Интерфейс за всички команди в системата за билетна каса.
 * <p>
 * Всеки клас, който представлява команда, трябва да имплементира
 * този интерфейс и да дефинира собствена логика в метода execute.
 */
public interface Command {

    /**
     * Изпълнява командата с подадените аргументи.
     *
     * @param args аргументи, въведени след името на командата
     */
    void execute(String[] args);
}
